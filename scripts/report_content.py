    ("h2", "4.2 无损 TSV 文本化与提示词构造"),
    ("p", "表格上下文方案经历了从「智能摘要」到「无损搬运」的取舍。早期版本把表格压缩成「表头行 + 推断列类型 + 2 行样例」，压缩比很高，但在表内存在多个标注块的复杂表上，表头行识别会失败，导致数据起始行退化、列名变成占位符，模型把表头文本当数据计算，正确性受损。现在改为：Python 只搬运，语义判断全部交给模型——逐格原样输出为 TSV 文本，带行号与列字母坐标系；单元格文本截断到 24 字符、列数上限 40；只有超过 200 行才启动行数闸门，保留头 50 行与尾 10 行，并在提示中显式标注「第 X-Y 行已省略」。实测 500 行 × 8 列的大表提示只有 2867 字符、发送 60 行、省略 440 行；6 行小表仅 331 字符。提示词中同时写入「统计区域的首行必须是第一个真正的数据行」的约束，并让模型把认定的数据区写入 assumptions 字段供人工核对，显著减少了 COUNTA、MIN、INDEX 等对表头文本敏感函数的错算（例如把 =MIN(A2:A10) 纠正为 =MIN(A3:A10)）。跨表需求的上下文补齐同样关键：当需求要引用同一工作簿内的其他工作表（如「成绩来自表一成绩单」）时，除目标表以外，其余工作表也按同一 TSV 规则以「来源表（仅供引用）」的身份提供给模型，与目标表共享 4 万字符的上下文预算；超出预算的表会被显式列出，并提示模型「信息不足时返回 clarification，不要猜测列位置」。系统提示中还约定：必须逐格核对来源表的真实列字母与数据区，不得把目标表的布局套用到来源表上。该机制修复了一类真实故障——模型在看不到来源表内容时自行假设列位置，用学号列匹配、对姓名列求平均，写出整列 #DIV/0! 的错误公式。"),
